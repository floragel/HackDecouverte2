    private struct StoryRow: Decodable { let id: String; let image_url: String?; let text: String?; let text_style: Int?; let created_at: String; let author: Profile }
    private struct ViewRow: Decodable { let story_id: String }

    func stories() async throws -> [StoryGroup] {
        let me = try uid
        let since = ISO.string(Date().addingTimeInterval(-24 * 3600))
        // explicit FK: stories <-> profiles is also linked through story_views (bare embed is ambiguous, PGRST201)
        let rows: [StoryRow] = try await client.from("stories").select("id, image_url, text, text_style, created_at, author:profiles!stories_author_id_fkey(*)")
            .gt("created_at", value: since).order("created_at").execute().value
        if rows.isEmpty { return [] }
        let seen = Set((try await client.from("story_views").select("story_id").eq("viewer_id", value: me).execute().value as [ViewRow]).map(\.story_id))
        let grouped = Dictionary(grouping: rows, by: { $0.author.id })
        return grouped.values.map { list in
            StoryGroup(profile: list[0].author, stories: list.map { Story(id: $0.id, imageUrl: $0.image_url, text: $0.text, textStyle: $0.text_style ?? 0, createdAt: ISO.date($0.created_at)) },
                       seen: list.allSatisfy { seen.contains($0.id) } || list[0].author.id == me)
        }.sorted { ($0.profile.id == me ? 0 : 1, $0.seen ? 1 : 0) < ($1.profile.id == me ? 0 : 1, $1.seen ? 1 : 0) }
    }


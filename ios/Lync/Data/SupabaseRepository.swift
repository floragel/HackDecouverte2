    private struct ConnRow: Decodable { let requester_id: String; let addressee_id: String; let status: String }
    private struct FollowRow: Decodable { let followee_id: String }
    private struct ClassmateRow: Decodable { let profile_id: String; let shared_count: Int }

    private func myConnections() async throws -> [ConnRow] {
        let me = try uid
        return try await client.from("connections").select().or("requester_id.eq.\(me),addressee_id.eq.\(me)").execute().value
    }

    private func friendIds() async throws -> [String] {
        let me = try uid
        return try await myConnections().filter { $0.status == "accepted" }.map { $0.requester_id == me ? $0.addressee_id : $0.requester_id }
    }

    private func peopleFor(_ profiles: [Profile], shared: [String: Int] = [:]) async throws -> [Person] {
        let me = try uid
        let conns = try await myConnections()
        let follows = Set((try await client.from("follows").select().eq("follower_id", value: me).execute().value as [FollowRow]).map(\.followee_id))
        return profiles.filter { $0.id != me }.map { pr in
            let c = conns.first { $0.requester_id == pr.id || $0.addressee_id == pr.id }
            let state: ConnectionState = c == nil ? .none : c!.status == "accepted" ? .connected : c!.requester_id == me ? .outgoing : .incoming
            return Person(profile: pr, sharedCourses: shared[pr.id] ?? 0, connection: state, following: follows.contains(pr.id))
        }
    }

    private func profilesById(_ ids: [String]) async throws -> [Profile] {
        if ids.isEmpty { return [] }
        return try await client.from("profiles").select().in("id", values: ids).execute().value
    }

    func requests() async throws -> [Person] {
        let me = try uid
        let ids = try await myConnections().filter { $0.status == "pending" && $0.addressee_id == me }.map(\.requester_id)
        return try await peopleFor(profilesById(ids))
    }

    func classmates() async throws -> [Person] {
        let rows: [ClassmateRow] = try await client.rpc("classmates", params: ["term_code": TERM]).execute().value
        let shared = Dictionary(uniqueKeysWithValues: rows.map { ($0.profile_id, $0.shared_count) })
        return try await peopleFor(profilesById(Array(shared.keys)), shared: shared).sorted { $0.sharedCourses > $1.sharedCourses }
    }

    func suggestions() async throws -> [Person] {
        let me = try uid
        let known = Set(try await myConnections().flatMap { [$0.requester_id, $0.addressee_id] } + [me])
        var q = client.from("profiles").select()
        if let program = session.me?.program { q = q.eq("program", value: program) }
        let list: [Profile] = try await q.limit(30).execute().value
        return try await peopleFor(list.filter { !known.contains($0.id) })
    }

    func clubs() async throws -> [Organization] {
        try await client.from("organizations").select().eq("university_id", value: session.me?.universityId ?? "").limit(20).execute().value
    }

    func search(_ query: String) async throws -> [Person] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard q.count >= 2 else { return [] }
        let list: [Profile] = try await client.from("profiles").select().or("full_name.ilike.%\(q)%,username.ilike.%\(q)%,program.ilike.%\(q)%").limit(20).execute().value
        return try await peopleFor(list)
    }

    func profile(_ id: String) async throws -> Person? { try await peopleFor(profilesById([id])).first }

    func profileByCode(_ code: Int64) async throws -> Person? {
        let list: [Profile] = try await client.from("profiles").select().eq("lync_code", value: Int(code)).execute().value
        guard let p = list.first else { return nil }
        return try await peopleFor([p]).first
    }

    func connect(_ profileId: String, source: String) async throws {
        try await client.from("connections").upsert(["requester_id": .string(try uid), "addressee_id": .string(profileId), "source": .string(source)] as Row).execute()
    }

    func respond(_ profileId: String, accept: Bool) async throws {
        let me = try uid
        if accept { try await client.from("connections").update(["status": "accepted"] as Row).eq("requester_id", value: profileId).eq("addressee_id", value: me).execute() }
        else { try await client.from("connections").delete().eq("requester_id", value: profileId).eq("addressee_id", value: me).execute() }
    }

    func setFollowing(_ profileId: String, _ follow: Bool) async throws {
        let me = try uid
        if follow { try await client.from("follows").upsert(["follower_id": .string(me), "followee_id": .string(profileId)] as Row).execute() }
        else { try await client.from("follows").delete().eq("follower_id", value: me).eq("followee_id", value: profileId).execute() }
    }


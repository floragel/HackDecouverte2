    private struct EventRow: Decodable {
        let id: String; let title: String; let description: String?; let category: String?; let starts_at: String; let ends_at: String
        let place: String?; let cover_url: String?; let featured: Bool?; let organizer: Organization; let event_rsvps: [CountRow]?
    }
    private struct RsvpRow: Decodable { let event_id: String; let profile_id: String }
    private let eventColumns = "id, title, description, category, starts_at, ends_at, place, cover_url, featured, organizer:organizations(id, name, handle, avatar_url, verified), event_rsvps(count)"

    private func toEvents(_ rows: [EventRow]) async throws -> [CampusEvent] {
        if rows.isEmpty { return [] }
        let me = try uid
        let rsvps: [RsvpRow] = try await client.from("event_rsvps").select().in("event_id", values: rows.map(\.id)).execute().value
        let friends = Set(try await friendIds())
        let friendProfiles = Dictionary(uniqueKeysWithValues: try await profilesById(Array(Set(rsvps.map(\.profile_id).filter { friends.contains($0) }))).map { ($0.id, $0) })
        return rows.map { r in
            let mine = rsvps.filter { $0.event_id == r.id }
            return CampusEvent(id: r.id, title: r.title, description: r.description ?? "", organizer: r.organizer, category: .of(r.category),
                               startsAt: ISO.date(r.starts_at), endsAt: ISO.date(r.ends_at), place: r.place ?? "", coverUrl: r.cover_url,
                               goingCount: r.event_rsvps?.first?.count ?? mine.count, imGoing: mine.contains { $0.profile_id == me },
                               friendsGoing: mine.compactMap { friendProfiles[$0.profile_id] }, featured: r.featured ?? false)
        }
    }

    func events() async throws -> [CampusEvent] {
        try await toEvents(client.from("events").select(eventColumns).gt("ends_at", value: ISO.string(Date())).order("starts_at").limit(50).execute().value)

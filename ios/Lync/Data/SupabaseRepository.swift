import Foundation
import Supabase

private let TERM = "F2026"
typealias Row = [String: AnyJSON]

/// The real backend. Same queries and rules as the Android `SupabaseRepository.kt`.
final class SupabaseRepository: CampusRepository {
    let isDemo = false
    let session = SessionState()
    private let client: SupabaseClient

    init(client: SupabaseClient) { self.client = client }

    private var uid: String {
        get throws {
            guard let id = client.auth.currentUser?.id.uuidString.lowercased() else { throw LyncError.message("Not signed in") }
            return id
        }
    }

    func restore() async {
        guard let id = try? await client.auth.session.user.id.uuidString.lowercased() else { return }
        session.me = try? await client.from("profiles").select().eq("id", value: id).single().execute().value as Profile
    }

    private func upload(_ bucket: String, _ data: Data) async throws -> String {
        let path = "\(try uid)/\(UUID().uuidString).jpg"
        _ = try await client.storage.from(bucket).upload(path, data: data, options: FileOptions(contentType: "image/jpeg"))
        return try client.storage.from(bucket).getPublicURL(path: path).absoluteString
    }

    func universities() async throws -> [University] {
        try await client.from("universities").select().order("name").execute().value
    }

    func university(_ id: String) async throws -> University? {
        let list: [University] = try await client.from("universities").select().eq("id", value: id).execute().value
        return list.first
    }

    func signUp(_ form: SignUpForm) async throws -> Profile {
        let email = form.email.trimmingCharacters(in: .whitespaces).lowercased()
        _ = try await client.auth.signUp(email: email, password: form.password)
        if client.auth.currentUser == nil { _ = try await client.auth.signIn(email: email, password: form.password) }
        let id = try uid
        let local = email.split(separator: "@").first.map { String($0).trimmingCharacters(in: CharacterSet(charactersIn: ".")) } ?? "student"
        let row: Row = [
            "id": .string(id), "university_id": .string(form.university.id),
            "username": .string("\(local)-\(UUID().uuidString.prefix(4).lowercased())"),
            "full_name": .string(form.fullName.trimmingCharacters(in: .whitespaces)),
            "program": form.program.isEmpty ? .null : .string(form.program),
            "year": form.year.map { .integer($0) } ?? .null,
        ]
        try await client.from("profiles").upsert(row).execute()
        // lync_code is generated by the database
        let saved: Profile = try await client.from("profiles").select().eq("id", value: id).single().execute().value
        session.me = saved
        return saved
    }

    func signIn(email: String, password: String) async throws -> Profile {
        _ = try await client.auth.signIn(email: email.trimmingCharacters(in: .whitespaces).lowercased(), password: password)
        let list: [Profile] = try await client.from("profiles").select().eq("id", value: try uid).execute().value
        guard let p = list.first else { throw LyncError.message("No Lync profile for this account yet. Create an account instead.") }
        session.me = p
        return p
    }

    func signOut() async {
        await clearLocation() // don't leave a last position behind
        try? await client.auth.signOut()
        session.me = nil
    }

    func updateProfile(_ edit: ProfileEdit) async throws {
        var row: Row = [
            "full_name": .string(edit.fullName.trimmingCharacters(in: .whitespaces)),
            "bio": edit.bio.isEmpty ? .null : .string(edit.bio),
            "program": edit.program.map { .string($0) } ?? .null,
            "year": edit.year.map { .integer($0) } ?? .null,
            "interests": .array(edit.interests.map { .string($0) }),
        ]
        if let avatar = edit.avatar { row["avatar_url"] = .string(try await upload("avatars", avatar)) }
        let id = try uid
        try await client.from("profiles").update(row).eq("id", value: id).execute()
        session.me = try await client.from("profiles").select().eq("id", value: id).single().execute().value
    }

    func updateStatus(_ key: String?) async throws {
        try await client.from("profiles").update(["status_key": key.map { AnyJSON.string($0) } ?? .null] as Row).eq("id", value: try uid).execute()
        session.me?.statusKey = key
    }

    func setLocationSharing(_ mode: LocationSharing) async throws {
        try await client.from("profiles").update(["location_sharing": AnyJSON.string(mode.rawValue)] as Row).eq("id", value: try uid).execute()
        session.me?.locationSharing = mode
        if mode == .off { await clearLocation() }
    }

    func stats(_ profileId: String?) async throws -> ProfileStats {
        let id = try profileId ?? uid
        async let posts = client.from("posts").select("id", head: true, count: .exact).eq("author_id", value: id).execute().count
        async let conns = client.from("connections").select("status", head: true, count: .exact).eq("status", value: "accepted")
            .or("requester_id.eq.\(id),addressee_id.eq.\(id)").execute().count
        async let followers = client.from("follows").select("followee_id", head: true, count: .exact).eq("followee_id", value: id).execute().count
        return ProfileStats(posts: try await posts ?? 0, connections: try await conns ?? 0, followers: try await followers ?? 0)
    }

    private struct EnrollmentRow: Decodable { let course: Course }

    func myCourses() async throws -> [Course] {
        let rows: [EnrollmentRow] = try await client.from("enrollments").select("course:courses(id, code, title)")
            .eq("profile_id", value: try uid).eq("term", value: TERM).execute().value
        return rows.map(\.course)
    }


    }

    private struct IdRow: Decodable { let id: String }

    func createPost(_ draft: PostDraft, groupId: String?) async throws {
        guard let me = session.me else { throw LyncError.message("No profile") }
        var row: Row = ["author_id": .string(try uid), "university_id": .string(me.universityId)]
        if let groupId { row["group_id"] = .string(groupId) }
        switch draft {
        case .photo(let image, let caption): row["kind"] = "photo"; row["image_url"] = .string(try await upload("posts", image)); row["caption"] = .string(caption)
        case .text(let text, let style): row["kind"] = "text"; row["caption"] = .string(text); row["text_style"] = .integer(style)
        case .poll(let q, _, let hours): row["kind"] = "poll"; row["poll_question"] = .string(q); row["poll_ends_at"] = .string(ISO.string(Date().addingTimeInterval(Double(hours) * 3600)))
        case .plan(let activity, let place, let startsAt, let spots, let note):
            row["kind"] = "plan"; row["caption"] = .string(note); row["plan_activity"] = .string(activity.rawValue)
            row["plan_place"] = .string(place); row["plan_starts_at"] = .string(ISO.string(startsAt)); row["plan_spots"] = spots.map { .integer($0) } ?? .null
        }
        let id = (try await client.from("posts").insert(row, returning: .representation).select("id").single().execute().value as IdRow).id
        switch draft {
        case .poll(_, let options, _):
            let rows: [Row] = options.enumerated().map { ["post_id": .string(id), "text": .string($0.element), "position": .integer($0.offset)] }
            try await client.from("poll_options").insert(rows).execute()
        case .plan: try await client.from("plan_participants").insert(["post_id": .string(id), "profile_id": .string(try uid)] as Row).execute()
        default: break
        }
    }

    func vote(_ postId: String, optionId: String) async throws {

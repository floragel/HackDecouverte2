    func createGroup(name: String, emoji: String, description: String) async throws -> InterestGroup {
        guard let me = session.me else { throw LyncError.message("No profile") }
        let row: Row = ["university_id": .string(me.universityId), "name": .string(name), "emoji": .string(emoji), "description": .string(description), "created_by": .string(try uid)]
        let id = (try await client.from("groups").insert(row, returning: .representation).select("id").single().execute().value as IdRow).id
        try await client.from("group_members").insert(["group_id": .string(id), "profile_id": .string(try uid)] as Row).execute()
        guard let g = try await group(id) else { throw LyncError.message("Group not found") }
        return g
    }

    // MARK: map

    private struct LocationRow: Decodable { let profile_id: String; let lat: Double; let lng: Double; let updated_at: String }

    func pushLocation(lat: Double, lng: Double) async throws {
        guard session.me?.locationSharing != .off else { return }
        try await client.from("locations").upsert(["profile_id": .string(try uid), "lat": .double(lat), "lng": .double(lng), "updated_at": .string(ISO.string(Date()))] as Row).execute()
    }

    func clearLocation() async {
        guard let me = try? uid else { return }
        _ = try? await client.from("locations").delete().eq("profile_id", value: me).execute()
    }

    private func fetchPins() async throws -> [MapPin] {
        let me = try uid
        let since = ISO.string(Date().addingTimeInterval(-2 * 3600))
        // RLS returns only the rows I'm allowed to see (friends / classmates who opted in)
        let rows: [LocationRow] = try await client.from("locations").select().neq("profile_id", value: me).gt("updated_at", value: since).execute().value
        if rows.isEmpty { return [] }
        let friends = Set(try await friendIds())
        let profiles = Dictionary(uniqueKeysWithValues: try await profilesById(rows.map(\.profile_id)).map { ($0.id, $0) })
        return rows.compactMap { r in
            guard let pr = profiles[r.profile_id] else { return nil }
            return MapPin(profile: pr, lat: r.lat, lng: r.lng, updatedAt: ISO.date(r.updated_at), kind: friends.contains(r.profile_id) ? .friend : .classmate)
        }
    }

    func mapPins() -> AsyncStream<[MapPin]> {
        AsyncStream { cont in
            let channel = client.channel("locations-live-\(UUID().uuidString.prefix(6))")
            let changes = channel.postgresChange(AnyAction.self, schema: "public", table: "locations")
            let live = Task {
                await channel.subscribe()
                // every insert/update on `locations` the user may see triggers a refresh
                for await _ in changes { if let pins = try? await fetchPins() { cont.yield(pins) } }
            }
            let poll = Task {
                while !Task.isCancelled {
                    if let pins = try? await fetchPins() { cont.yield(pins) }
                    try? await Task.sleep(nanoseconds: 15_000_000_000) // safety net if realtime drops
                }
            }
            cont.onTermination = { [client] _ in
                live.cancel(); poll.cancel()
                Task { await client.removeChannel(channel) }
            }
        }
    }
}

enum SupabaseProvider {
    static var url: String { (Bundle.main.object(forInfoDictionaryKey: "SUPABASE_URL") as? String ?? "").trimmingCharacters(in: .whitespaces) }
    static var key: String { (Bundle.main.object(forInfoDictionaryKey: "SUPABASE_KEY") as? String ?? "").trimmingCharacters(in: .whitespaces) }
    static var forceDemo: Bool { (Bundle.main.object(forInfoDictionaryKey: "LYNC_DEMO") as? String ?? "NO").uppercased() == "YES" }
    static var isConfigured: Bool { !forceDemo && url.hasPrefix("http") && !key.isEmpty }

    static func create() -> SupabaseClient? {
        let clean = url.components(separatedBy: "/rest/").first ?? url
        guard let u = URL(string: clean.trimmingCharacters(in: CharacterSet(charactersIn: "/"))) else { return nil }
        return SupabaseClient(supabaseURL: u, supabaseKey: key)
    }
}

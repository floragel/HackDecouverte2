    private func toFeed(_ rows: [PostRow]) async throws -> [FeedPost] {
        if rows.isEmpty { return [] }
        let me = try uid
        let ids: [any PostgrestFilterValue] = rows.map(\.id)
        let liked = Set((try await client.from("likes").select("post_id").eq("profile_id", value: me).in("post_id", values: ids).execute().value as [PostIdRow]).map(\.post_id))
        let pollIds: [any PostgrestFilterValue] = rows.filter { $0.kind == "poll" }.map(\.id)
        let votes: [VoteRow] = pollIds.isEmpty ? [] : try await client.from("poll_votes").select().in("post_id", values: pollIds).execute().value
        let planIds: [any PostgrestFilterValue] = rows.filter { $0.kind == "plan" }.map(\.id)
        let going: [GoingRow] = planIds.isEmpty ? [] : try await client.from("plan_participants").select("post_id, profile:profiles(*)").in("post_id", values: planIds).execute().value

        return rows.map { r in
            let org = r.organization
            let kind = PostKind(rawValue: r.kind ?? "photo") ?? .photo
            var post = FeedPost(id: r.id, authorId: org?.id ?? r.author?.id ?? "", authorName: org?.name ?? r.author?.full_name ?? "",
                                authorHandle: org?.handle ?? r.author?.username ?? "", authorAvatar: org?.avatarUrl ?? r.author?.avatar_url,
                                isOrganization: org != nil, verified: org?.verified ?? false, imageUrl: r.image_url, caption: r.caption,
                                createdAt: ISO.date(r.created_at), likeCount: r.likes?.first?.count ?? 0, likedByMe: liked.contains(r.id),
                                sponsored: r.is_sponsored ?? false, kind: kind, textStyle: r.text_style ?? 0, commentCount: r.comments?.first?.count ?? 0)
            if kind == .poll {
                let v = votes.filter { $0.post_id == r.id }
                post.poll = Poll(question: r.poll_question ?? "",
                                 options: (r.poll_options ?? []).sorted { ($0.position ?? 0) < ($1.position ?? 0) }.map { o in PollOption(id: o.id, text: o.text, votes: v.filter { $0.option_id == o.id }.count) },
                                 myVote: v.first { $0.profile_id == me }?.option_id, endsAt: ISO.date(r.poll_ends_at))
            }
            if kind == .plan {
                let g = going.filter { $0.post_id == r.id }.map(\.profile)
                post.plan = Plan(activity: .of(r.plan_activity), place: r.plan_place ?? "", startsAt: ISO.date(r.plan_starts_at), spots: r.plan_spots, going: g, imGoing: g.contains { $0.id == me })
            }
            return post
        }
    }

    func feed() async throws -> [FeedPost] {
        try await toFeed(client.from("posts").select(postColumns).is("group_id", value: nil).order("created_at", ascending: false).limit(50).execute().value)

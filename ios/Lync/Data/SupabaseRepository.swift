    private struct GroupRow: Decodable { let id: String; let name: String; let emoji: String?; let description: String?; let group_members: [CountRow]? }
    private struct MemberRow: Decodable { let group_id: String; let profile: Profile }
    private let groupColumns = "id, name, emoji, description, group_members(count)"

    private func toGroups(_ rows: [GroupRow]) async throws -> [InterestGroup] {
        if rows.isEmpty { return [] }
        let me = try uid
        let members: [MemberRow] = try await client.from("group_members").select("group_id, profile:profiles(*)").in("group_id", values: rows.map(\.id)).limit(400).execute().value
        return rows.map { r in
            let m = members.filter { $0.group_id == r.id }.map(\.profile)
            return InterestGroup(id: r.id, name: r.name, emoji: r.emoji ?? "✨", description: r.description ?? "", memberCount: r.group_members?.first?.count ?? m.count,
                                 isMember: m.contains { $0.id == me }, members: Array(m.prefix(8)))
        }.sorted { $0.isMember && !$1.isMember }
    }

    func groups() async throws -> [InterestGroup] { try await toGroups(client.from("groups").select(groupColumns).limit(50).execute().value) }

    @Serializable private data class IdRow(val id: String)

    override suspend fun createPost(draft: PostDraft, groupId: String?): Result<Unit> = runCatching {
        val me = _me.value ?: error("No profile")
        val row = buildJsonObject {
            put("author_id", uid); put("university_id", me.universityId)
            groupId?.let { put("group_id", it) }
            when (draft) {
                is PostDraft.Photo -> { put("kind", "photo"); put("image_url", upload("posts", draft.image)); put("caption", draft.caption) }
                is PostDraft.Text -> { put("kind", "text"); put("caption", draft.text); put("text_style", draft.style) }
                is PostDraft.PollDraft -> {
                    put("kind", "poll"); put("poll_question", draft.question)
                    put("poll_ends_at", Instant.now().plusSeconds(draft.hours * 3600L).toString())
                }
                is PostDraft.PlanDraft -> {
                    put("kind", "plan"); put("caption", draft.note); put("plan_activity", draft.activity.key)
                    put("plan_place", draft.place); put("plan_starts_at", Instant.ofEpochMilli(draft.startsAtMillis).toString())
                    if (draft.spots != null) put("plan_spots", draft.spots) else put("plan_spots", JsonNull)
                }
            }
        }
        val id = client.from("posts").insert(row) { select(Columns.list("id")) }.decodeSingle<IdRow>().id
        when (draft) {
            is PostDraft.PollDraft -> client.from("poll_options").insert(buildJsonArray {
                draft.options.forEachIndexed { i, t -> add(buildJsonObject { put("post_id", id); put("text", t); put("position", i) }) }
            })
            is PostDraft.PlanDraft -> client.from("plan_participants").insert(buildJsonObject { put("post_id", id); put("profile_id", uid) })
            else -> Unit
        }
    }


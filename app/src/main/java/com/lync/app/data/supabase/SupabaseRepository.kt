    }

    override suspend fun respond(profileId: String, accept: Boolean) {
        if (accept) {
            client.from("connections").update({ set("status", "accepted") }) {
                filter { eq("requester_id", profileId); eq("addressee_id", uid) }
            }
        } else {
            client.from("connections").delete { filter { eq("requester_id", profileId); eq("addressee_id", uid) } }
        }
    }

    override suspend fun setFollowing(profileId: String, follow: Boolean) {
        if (follow) client.from("follows").upsert(buildJsonObject { put("follower_id", uid); put("followee_id", profileId) })
        else client.from("follows").delete { filter { eq("follower_id", uid); eq("followee_id", profileId) } }
    }


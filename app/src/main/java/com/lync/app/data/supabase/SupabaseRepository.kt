    private suspend fun myConnections(): List<ConnRow> =
        client.from("connections").select { filter { or { eq("requester_id", uid); eq("addressee_id", uid) } } }.decodeList()

    private suspend fun friendIds(): List<String> = myConnections().filter { it.status == "accepted" }
        .map { if (it.requesterId == uid) it.addresseeId else it.requesterId }

    private suspend fun peopleFor(profiles: List<Profile>, shared: Map<String, Int> = emptyMap()): List<Person> {
        val conns = myConnections()
        val follows = client.from("follows").select { filter { eq("follower_id", uid) } }.decodeList<FollowRow>().map { it.followeeId }.toSet()
        return profiles.filter { it.id != uid }.map { pr ->
            val c = conns.firstOrNull { it.requesterId == pr.id || it.addresseeId == pr.id }
            val state = when {
                c == null -> ConnectionState.NONE
                c.status == "accepted" -> ConnectionState.CONNECTED
                c.requesterId == uid -> ConnectionState.OUTGOING
                else -> ConnectionState.INCOMING
            }
            Person(pr, sharedCourses = shared[pr.id] ?: 0, connection = state, following = pr.id in follows)
        }
    }

    private suspend fun profilesById(ids: Collection<String>): List<Profile> =
        if (ids.isEmpty()) emptyList() else client.from("profiles").select { filter { isIn("id", ids.toList()) } }.decodeList()

    override suspend fun requests(): List<Person> {
        val ids = myConnections().filter { it.status == "pending" && it.addresseeId == uid }.map { it.requesterId }
        return peopleFor(profilesById(ids))
    }

    override suspend fun classmates(): List<Person> {
        val rows = client.postgrest.rpc("classmates", buildJsonObject { put("term_code", TERM) }).decodeList<ClassmateRow>()
        val shared = rows.associate { it.profileId to it.sharedCount }
        return peopleFor(profilesById(shared.keys), shared).sortedByDescending { it.sharedCourses }
    }

    override suspend fun suggestions(): List<Person> {
        val known = myConnections().flatMap { listOf(it.requesterId, it.addresseeId) }.toSet() + uid
        val sameProgram = client.from("profiles").select {
            _me.value?.program?.let { prog -> filter { eq("program", prog) } }
            limit(30)
        }.decodeList<Profile>()
        return peopleFor(sameProgram.filter { it.id !in known })
    }

    override suspend fun clubs(): List<Organization> =
        client.from("organizations").select { filter { eq("university_id", _me.value?.universityId ?: "") }; limit(20) }.decodeList()

    override suspend fun search(query: String): List<Person> {
        val q = query.trim()
        if (q.length < 2) return emptyList()
        val rows = client.from("profiles").select {
            filter { or { ilike("full_name", "%$q%"); ilike("username", "%$q%"); ilike("program", "%$q%") } }
            limit(20)
        }.decodeList<Profile>()
        return peopleFor(rows)
    }

    override suspend fun profile(id: String): Person? = peopleFor(profilesById(listOf(id))).firstOrNull()

    override suspend fun profileByCode(code: Long): Person? {
        val pr = client.from("profiles").select { filter { eq("lync_code", code) } }.decodeSingleOrNull<Profile>() ?: return null
        return peopleFor(listOf(pr)).firstOrNull()
    }

    override suspend fun connect(profileId: String, source: String) {
        client.from("connections").upsert(buildJsonObject {
            put("requester_id", uid); put("addressee_id", profileId); put("source", source)

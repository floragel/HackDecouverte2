    private val uid: String get() = client.auth.currentUserOrNull()?.id ?: error("Not signed in")

    /** Called at startup: restores the persisted session, then loads the profile. */
    suspend fun restore() {
        runCatching {
            client.auth.awaitInitialization()
            val id = client.auth.currentUserOrNull()?.id ?: return
            _me.value = client.from("profiles").select { filter { eq("id", id) } }.decodeSingleOrNull<Profile>()
        }
    }

    private fun ts(s: String?) = s?.let { runCatching { Instant.parse(it).toEpochMilli() }.getOrNull() } ?: 0L

    private suspend fun upload(bucket: String, bytes: ByteArray): String {
        val path = "$uid/${UUID.randomUUID()}.jpg"
        client.storage.from(bucket).upload(path, bytes)
        return client.storage.from(bucket).publicUrl(path)
    }

    override suspend fun universities(): List<University> =

    private suspend fun toFeed(rows: List<PostRow>): List<FeedPost> {
        if (rows.isEmpty()) return emptyList()
        val ids = rows.map { it.id }
        val liked = client.from("likes").select(Columns.list("post_id")) { filter { eq("profile_id", uid); isIn("post_id", ids) } }
            .decodeList<PostIdRow>().map { it.postId }.toSet()
        val pollIds = rows.filter { it.kind == "poll" }.map { it.id }
        val votes = if (pollIds.isEmpty()) emptyList() else
            client.from("poll_votes").select { filter { isIn("post_id", pollIds) } }.decodeList<VoteRow>()
        val planIds = rows.filter { it.kind == "plan" }.map { it.id }
        val going = if (planIds.isEmpty()) emptyList() else
            client.from("plan_participants").select(Columns.raw("post_id, profile:profiles(*)")) { filter { isIn("post_id", planIds) } }.decodeList<GoingRow>()

        return rows.map { r ->
            val org = r.organization
            val kind = runCatching { PostKind.valueOf(r.kind.uppercase()) }.getOrDefault(PostKind.PHOTO)
            FeedPost(
                id = r.id,
                authorId = org?.id ?: r.author?.id.orEmpty(),
                authorName = org?.name ?: r.author?.fullName.orEmpty(),
                authorHandle = org?.handle ?: r.author?.username.orEmpty(),
                authorAvatar = org?.avatarUrl ?: r.author?.avatarUrl,
                isOrganization = org != null, verified = org?.verified ?: false,
                imageUrl = r.imageUrl, caption = r.caption, createdAtMillis = ts(r.createdAt),
                likeCount = r.likes.firstOrNull()?.count ?: 0, likedByMe = r.id in liked, sponsored = r.isSponsored,
                kind = kind, textStyle = r.textStyle, commentCount = r.comments.firstOrNull()?.count ?: 0,
                poll = if (kind == PostKind.POLL) {
                    val v = votes.filter { it.postId == r.id }
                    Poll(
                        r.pollQuestion.orEmpty(),
                        r.pollOptions.sortedBy { it.position }.map { o -> PollOption(o.id, o.text, v.count { it.optionId == o.id }) },
                        v.firstOrNull { it.profileId == uid }?.optionId, ts(r.pollEndsAt),
                    )
                } else null,
                plan = if (kind == PostKind.PLAN) {
                    val g = going.filter { it.postId == r.id }.map { it.profile }
                    Plan(PlanActivity.of(r.planActivity), r.planPlace.orEmpty(), ts(r.planStartsAt), r.planSpots, g, g.any { it.id == uid })
                } else null,
            )
        }
    }


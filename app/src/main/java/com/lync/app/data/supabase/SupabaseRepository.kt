    override suspend fun university(id: String): University? =
        client.from("universities").select { filter { eq("id", id) } }.decodeSingleOrNull()

    override suspend fun signUp(form: SignUpForm): Result<Profile> = runCatching {
        val email = form.email.trim().lowercase()
        require(email.endsWith("@${form.university.emailDomain}") || email.endsWith(".${form.university.emailDomain}")) {
            "Use your ${form.university.emailDomain} email"
        }
        client.auth.signUpWith(Email) { this.email = email; password = form.password }
        if (client.auth.currentUserOrNull() == null) {
            client.auth.signInWith(Email) { this.email = email; password = form.password }
        }
        val profile = Profile(
            id = uid, universityId = form.university.id,
            username = email.substringBefore('@').trimEnd('.') + "-" + UUID.randomUUID().toString().take(4),
            fullName = form.fullName.trim(), program = form.program.ifBlank { null }, year = form.year,
        )
        client.from("profiles").upsert(profile)
        // lync_code is generated by the database (unique random 32-bit number)
        val saved = client.from("profiles").select { filter { eq("id", uid) } }.decodeSingle<Profile>()
        _me.value = saved
        saved
    }

    override suspend fun signIn(email: String, password: String): Result<Profile> = runCatching {
        client.auth.signInWith(Email) { this.email = email.trim().lowercase(); this.password = password }
        val profile = client.from("profiles").select { filter { eq("id", uid) } }.decodeSingleOrNull<Profile>()
            ?: error("No Lync profile for this account yet. Create an account instead.")
        _me.value = profile
        profile
    }

    override suspend fun signOut() {
        runCatching { client.auth.signOut() }
        _me.value = null
    }

    override suspend fun updateProfile(edit: ProfileEdit): Result<Unit> = runCatching {
        val avatarUrl = edit.avatar?.let { upload("avatars", it) }
        client.from("profiles").update({
            set("full_name", edit.fullName.trim())
            set("bio", edit.bio.ifBlank { null })
            set("program", edit.program)
            set("year", edit.year)
            set("interests", edit.interests)
            if (avatarUrl != null) set("avatar_url", avatarUrl)
        }) { filter { eq("id", uid) } }
        _me.value = client.from("profiles").select { filter { eq("id", uid) } }.decodeSingle<Profile>()
    }

    override suspend fun updateStatus(key: String?) {
        client.from("profiles").update({ set("status_key", key) }) { filter { eq("id", uid) } }
        _me.value = _me.value?.copy(statusKey = key)
    }

    override suspend fun setLocationSharing(mode: LocationSharing) {
        client.from("profiles").update({ set("location_sharing", mode) }) { filter { eq("id", uid) } }
        _me.value = _me.value?.copy(locationSharing = mode)
        if (mode == LocationSharing.OFF) clearLocation()
    }

    override suspend fun stats(profileId: String?): ProfileStats {
        val id = profileId ?: uid
        suspend fun count(table: String, block: PostgrestRequestBuilder.() -> Unit): Int =
            client.from(table).select(Columns.list("created_at")) { count(Count.EXACT); limit(1); block() }.countOrNull()?.toInt() ?: 0
        return ProfileStats(
            posts = count("posts") { filter { eq("author_id", id) } },
            connections = count("connections") { filter { eq("status", "accepted"); or { eq("requester_id", id); eq("addressee_id", id) } } },
            followers = count("follows") { filter { eq("followee_id", id) } },
        )
    }


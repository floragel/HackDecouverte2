    override suspend fun stories(): List<StoryGroup> {
        val since = Instant.now().minusSeconds(24 * 3600).toString()
        val rows = client.from("stories").select(Columns.raw("id, image_url, text, text_style, created_at, author:profiles(*)")) {
            filter { gt("created_at", since) }; order("created_at", Order.ASCENDING)
        }.decodeList<StoryRow>()
        if (rows.isEmpty()) return emptyList()
        val seen = client.from("story_views").select(Columns.list("story_id")) { filter { eq("viewer_id", uid) } }
            .decodeList<ViewRow>().map { it.storyId }.toSet()
        return rows.groupBy { it.author.id }.map { (_, list) ->
            StoryGroup(list.first().author, list.map { Story(it.id, it.imageUrl, it.text, it.textStyle, ts(it.createdAt)) },
                seen = list.all { it.id in seen } || list.first().author.id == uid)
        }.sortedWith(compareBy({ it.profile.id != uid }, { it.seen }))
    }

